"""Browser acceptance on loopback only. No production credentials or provider calls."""
import os
import socket
import tempfile
import threading
import time
import unittest
from pathlib import Path
from unittest.mock import patch
import uvicorn
from playwright.sync_api import sync_playwright, expect
from platform_core.chat_api import create_app
from platform_core.guest_registration import RegistrationStore
from platform_core.account_access import AccountAccess
from tests.auth_fixture import email_opted_out

P="fixture-browser-password"
class AccountingBrowser(unittest.TestCase):
    def test_accounting_workflow(self):
        self.enterContext(patch.dict(os.environ,{"PODMASTERYE_MULTI_WORKSHOP":"1"}))
        root=Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.enterContext(patch.dict(os.environ,{"HARNESS_OFFLINE_MODEL":"0","HARNESS_USAGE_JOURNAL":str(root/"usage.jsonl")}))
        os.environ.pop("HARNESS_MODEL_GATEWAY_URL",None)
        db=root/"test.sqlite3"
        with RegistrationStore(db) as store:
            AccountAccess(store)
            store.create_account("owner",P);email_opted_out(store,"owner")
            store.create_account("administrator",P);store.set_admin("administrator",True)
            token=store.login("administrator",P)
        sock=socket.socket();sock.bind(("127.0.0.1",0));sock.listen(64)
        origin="http://127.0.0.1:"+str(sock.getsockname()[1])
        app=create_app(db,root/"chats")
        server=uvicorn.Server(uvicorn.Config(app,log_level="warning",access_log=False))
        thread=threading.Thread(target=server.run,kwargs={"sockets":[sock]},daemon=True);thread.start()
        def stop():
            server.should_exit=True;thread.join(timeout=10);sock.close()
        self.addCleanup(stop)
        deadline=time.monotonic()+10
        while not server.started:
            self.assertLess(time.monotonic(),deadline);time.sleep(.05)
        with sync_playwright() as pw:
            browser=pw.chromium.launch(headless=True,args=["--no-sandbox"])
            ctx=browser.new_context(accept_downloads=True,viewport={"width":1440,"height":1000},locale="ru-RU")
            page=ctx.new_page();errors=[];page.on("pageerror",lambda e:errors.append(str(e)))
            page.goto(origin+"/login")
            page.get_by_label("Логин",exact=True).fill("owner")
            page.get_by_label("Пароль",exact=True).fill(P)
            page.get_by_role("button",name="Войти",exact=True).click()
            expect(page.locator("body")).to_have_attribute("data-mode","member")
            expect(page.locator("#assistant-form button[type=submit]")).to_be_enabled()
            expect(page.locator("#balance-label")).to_contain_text("10 монет")
            def ask(text):
                page.locator("#assistant-form textarea").fill(text)
                with page.expect_response(lambda r:"/turns" in r.url and r.request.method=="POST") as got:
                    page.locator("#assistant-form button[type=submit]").click()
                self.assertEqual(got.value.status,200,got.value.text())
                expect(page.locator("#assistant-status")).to_have_text("")
                return got.value.json()
            def nav(section):
                with page.expect_response(lambda r:"/api/accounting?" in r.url) as got:
                    page.locator('nav button[data-page="'+section+'"]').click()
                self.assertEqual(got.value.status,200)
                expect(page.locator('[data-panel="'+section+'"]')).to_be_visible()
            def write(section,op,values,expect_summary):
                nav(section)
                page.locator('[data-book-op="'+op+'"]').click()
                dlg=page.locator("#book-dialog")
                expect(dlg).to_be_visible()
                for name,value in values.items():
                    el=dlg.locator('[name="'+name+'"]')
                    if isinstance(value,bool):el.set_checked(value)
                    elif el.evaluate("el => el.tagName")=="SELECT":
                        if value=="__first__":el.select_option(index=1)
                        else:el.select_option(value=str(value))
                    else:el.fill(str(value))
                dlg.locator("#book-check").click()
                expect(dlg.locator("#book-preview")).to_contain_text(expect_summary)
                expect(dlg.locator("#book-confirm")).to_be_enabled()
                with page.expect_response(lambda r:"/api/accounting/commit" in r.url) as got:
                    dlg.locator("#book-confirm").click()
                self.assertEqual(got.value.status,200,got.value.text())
                expect(dlg).not_to_be_visible()
                expect(page.locator("#accounting-status")).to_contain_text(expect_summary)
                return got.value.json()
            answer=ask("Добавь бусины пачками по 400 штук, на браслет уходит 40 штук, упаковка стоит 800 рублей")
            self.assertEqual(answer["route"],"local")
            page.locator("#recipe-form").get_by_role("button",name="Сохранить",exact=True).click()
            expect(page.locator("#products")).to_contain_text("браслет")
            write("purchases","purchase",{"material":"__first__","quantity":2,"total":"1600","supplier":"Тест"},"1600.00")
            write("manufacture","manufacture",{"product":"__first__","quantity":3},"240.00")
            sale=write("sales","sale",{"product":"__first__","quantity":4,"unit_price":"300","paid_amount":"1200","auto_produce":True},"320.00")
            write("expenses","expense",{"category":"Реклама","total":"100"},"100.00")
            a=ask("покажи чистую прибыль за этот месяц")
            self.assertIn("780.00",a["text"])
            expect(page.locator('[data-panel="finance"] [data-metric="net_profit"]')).to_contain_text("780.00")
            expect(page.locator('[data-panel="finance"] [data-metric="net_profit"]')).to_have_class("metric highlight")
            a=ask("сколько бусин осталось")
            self.assertIn("640",a["text"])
            expect(page.locator("#stock-raw")).to_contain_text("640 шт")
            expect(page.locator("#catalog-filter")).to_have_value("бусины")
            page.locator("#catalog-filter").fill("")
            nav("sales")
            page.locator("#sales-current").get_by_role("button",name="Возврат",exact=True).click()
            dlg=page.locator("#book-dialog")
            dlg.locator('[name="quantity"]').fill("1")
            dlg.locator('[name="refund"]').fill("300")
            dlg.locator('[name="restock"]').check()
            dlg.locator("#book-check").click();expect(dlg.locator("#book-preview")).to_contain_text("300.00")
            dlg.locator("#book-confirm").click();expect(dlg).not_to_be_visible()
            nav("finance")
            expect(page.locator('[data-panel="finance"] [data-metric="net_profit"]')).to_contain_text("560.00")
            with page.expect_download() as download:page.get_by_role("link",name="Выгрузить весь учёт XLSX").click()
            self.assertEqual(download.value.suggested_filename,"podmasterye-accounting.xlsx")
            self.assertTrue(download.value.path().stat().st_size>0)
            self.assertEqual(page.locator(".receipt").count(),0)
            expect(page.locator("#balance-label")).to_contain_text("10 монет")
            out=os.getenv("PODMASTER_BROWSER_EVIDENCE")
            if out:page.screenshot(path=str(Path(out)/"accounting-finance.png"),full_page=True)
            # Verify additional sections, layout controls, calculator, and isolated demo.
            page.locator("#toggle-nav").click();expect(page.locator("nav")).not_to_be_visible()
            page.locator("#toggle-nav").click();expect(page.locator("nav")).to_be_visible()
            page.locator("#toggle-helper").click();expect(page.locator("aside")).not_to_be_visible()
            page.locator("#toggle-helper").click();expect(page.locator("aside")).to_be_visible()
            page.locator("#theme-quick").click();expect(page.locator("html")).to_have_attribute("data-theme","dark")
            page.locator("#theme-quick").click();expect(page.locator("html")).to_have_attribute("data-theme","light")
            ask("создать задачу")
            dlg=page.locator("#book-dialog");expect(dlg).to_be_visible()
            dlg.locator('[name="name"]').fill("Упаковать заказ")
            dlg.locator('[name="task_category"]').select_option("Заказ")
            dlg.locator("#book-check").click();expect(dlg.locator("#book-preview")).to_contain_text("Упаковать заказ")
            dlg.locator("#book-confirm").click();expect(dlg).not_to_be_visible()
            expect(page.locator("#tasks-list")).to_contain_text("Упаковать заказ")
            nav("unit");expect(page.locator("#unit-table")).to_contain_text("браслет")
            nav("materials")
            page.locator('#import-form input[type="file"]').set_input_files({"name":"test.csv","mimeType":"text/csv","buffer":"name;unit;pack;pack_price\nНить;шт;100;250\n".encode()})
            page.locator("#import-form button").click();expect(page.locator("#import-status")).to_contain_text("Проверено 1")
            page.locator("#import-commit").click();expect(page.locator("#import-status")).to_contain_text("Загружено материалов: 1")
            expect(page.locator("#materials")).to_contain_text("Нить")
            nav("integrations");expect(page.locator("#sources-list")).to_contain_text("Нет подключённых магазинов")
            page.locator('#source-create input[name="name"]').fill("Учебный магазин")
            page.locator("#source-create button:not([type=button])").click();expect(page.locator("#source-key-box")).to_be_visible()
            page.locator("#source-hide").click();expect(page.locator("#source-key-box")).not_to_be_visible()
            expect(page.locator("#sources-list")).to_contain_text("Учебный магазин")
            # New local manufacturing and financial operations, with real forms.
            write("manufacture","work_start",{"product":"__first__","quantity":2},"160.00")
            expect(page.locator("#wip-list")).to_contain_text("160.00")
            write("manufacture","work_finish",{"product":"__first__","quantity":1,"extra":"20"},"100.00")
            expect(page.locator("#wip-list")).to_contain_text("80.00")
            write("sales","sale_fee",{"sale":"__first__","category":"Комиссия","total":"30"},"30.00")
            write("assets","asset_acquire",{"name":"Тестовый станок","total":"12000","months":12,"paid":False},"12000.00")
            expect(page.locator("#assets-list")).to_contain_text("Тестовый станок")
            nav("unit")
            page.locator("#cost-policy-open").click()
            dlg=page.locator("#book-dialog")
            dlg.locator('[name="monthly_overhead"]').fill("2000")
            dlg.locator('[name="productive_hours"]').fill("100")
            dlg.locator('[name="include_depreciation"]').check()
            dlg.locator("#book-check").click()
            expect(dlg.locator("#book-preview")).to_contain_text("Политика")
            dlg.locator("#book-confirm").click();expect(dlg).not_to_be_visible()
            expect(page.locator("#cost-policy-info")).to_contain_text("на час: 30.00 ₽")
            nav("expenses")
            row=page.locator('[data-event-table="expenses"] tbody tr').filter(has_text="Расход: Реклама")
            row.get_by_role("button",name="Изменить",exact=True).click()
            dlg=page.locator("#book-dialog")
            dlg.locator('[name="total"]').fill("120")
            dlg.locator("#book-correction-reason").fill("Проверка исторического пересчёта")
            dlg.locator("#book-check").click()
            expect(dlg.locator("#book-preview")).to_contain_text("Журнал пересчитан")
            dlg.locator("#book-confirm").click();expect(dlg).not_to_be_visible()
            nav("journal");expect(page.locator("#correction-history")).to_contain_text("Проверка исторического пересчёта")
            nav("products")
            page.locator("#products").get_by_role("button",name="Карточка",exact=True).first.click()
            expect(page.locator("#product-detail")).to_be_visible()
            expect(page.locator("#product-detail-body")).to_contain_text("Материал")
            page.locator("#product-detail-close").click()
            nav("finance")
            expect(page.locator("#finance-monthly")).to_contain_text("Амортизация")
            if out:page.screenshot(path=str(Path(out)/"accounting-v5-finance.png"),full_page=True)
            nav("settings")
            page.locator("#workshop-demo").click();expect(page.locator("#workshop-caption")).to_contain_text("Демонстрационная")
            expect(page.locator("#assistant-form button[type=submit]")).to_be_enabled()
            nav("finance");expect(page.locator('[data-panel="finance"] [data-metric="net_profit"]')).to_contain_text("1000.00")
            page.set_viewport_size({"width":390,"height":844})
            expect(page.locator("nav")).not_to_be_visible()
            page.locator("#toggle-nav").click();expect(page.locator("nav")).to_be_visible()
            page.locator('nav button[data-page="summary"]').click();expect(page.locator("nav")).not_to_be_visible()
            self.assertLessEqual(page.evaluate("document.documentElement.scrollWidth"),390)
            page.locator("#toggle-helper").click();expect(page.locator("aside")).to_be_visible()
            if out:page.screenshot(path=str(Path(out)/"accounting-mobile.png"),full_page=True)
            page.locator("#close-helper").click();expect(page.locator("aside")).not_to_be_visible()
            page.goto(origin+"/kalkulyator")
            page.locator('[name="product_name"]').fill("Тест калькулятора")
            page.locator('#calc-rows [name="name"]').fill("Воск")
            page.locator('#calc-rows [name="quantity"]').fill("0.25")
            page.locator('#calc-rows [name="unit"]').select_option("кг")
            page.locator('#calc-rows [name="price"]').fill("500")
            page.locator('[name="sale_price"]').fill("400")
            page.locator('[name="minutes"]').fill("30")
            page.locator('[name="hourly_rate"]').fill("200")
            page.get_by_role("button",name="Рассчитать",exact=True).click()
            expect(page.locator("#calc-result")).to_contain_text("175.00 ₽")
            admin_ctx=browser.new_context();admin_ctx.add_cookies([{"name":"podmaster_local_session","value":token,"url":origin,"httpOnly":True,"sameSite":"Strict"}])
            admin=admin_ctx.new_page();admin.on("pageerror",lambda e:errors.append(str(e)))
            admin.goto(origin+"/app/")
            expect(admin.locator("body")).to_have_attribute("data-admin","1")
            expect(admin.locator("#assistant-form button[type=submit]")).to_be_enabled()
            admin.locator("#assistant-form textarea").fill("как считается прибыль")
            admin.locator("#assistant-form button[type=submit]").click()
            expect(admin.locator(".receipt").last).to_contain_text("0 ₽")
            self.assertFalse((root/"usage.jsonl").exists())
            self.assertEqual(errors,[])
            admin_ctx.close();ctx.close()
