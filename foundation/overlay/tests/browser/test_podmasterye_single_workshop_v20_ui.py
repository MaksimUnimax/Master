"""Acceptance of one-workshop UI and symmetric surface controls."""
import os
from unittest.mock import patch
from playwright.sync_api import expect
from test_podmasterye_independent_ui import IndependentUI

class SingleWorkshopUI(IndependentUI):
    def test_single_workshop_and_equal_controls(self):
        self.enterContext(patch.dict(os.environ,{"PODMASTERYE_MULTI_WORKSHOP":"0"}))
        self.sign_in()
        p=self.page
        for selector in ("#workshop-select","#workshop-create","#workshop-demo","#workshop-list"):
            expect(p.locator(selector)).to_have_count(0)
        self.nav("settings")
        form=p.locator("#workshop-settings")
        form.locator("[name=name]").fill("Моя студия")
        form.locator("[name=hourly_rate]").fill("350")
        form.get_by_role("button",name="Сохранить",exact=True).click()
        expect(p.locator("#workshop-status")).to_have_text("Настройки сохранены.")
        wid=p.evaluate("window.PMWorkshopId")
        p.goto("/app/?workshop=obsolete-id")
        self.ready()
        self.assertEqual(p.evaluate("window.PMWorkshopId"),wid)
        self.nav("settings")
        expect(form.locator("[name=name]")).to_have_value("Моя студия")
        expect(form.locator("[name=hourly_rate]")).to_have_value("350.00")
        helper=p.locator("#assistant-pane")
        work=p.locator("#work-pane")
        nav=p.locator(".layout>nav")
        left=p.locator("#close-helper")
        right=p.locator("#expand-work")
        menu=p.locator("#close-nav")
        expect(right).to_have_text("Помощник")
        right.click()
        expect(helper).to_be_visible()
        expect(work).to_be_visible()
        for width in (1440,1920,1100):
            p.set_viewport_size({"width":width,"height":800})
            for theme in ("light","dark"):
                p.evaluate("(v)=>window.PMTheme.set(v)",theme)
                expect(left).to_have_text("Свернуть")
                expect(right).to_have_text("Свернуть")
                expect(menu).to_have_text("Свернуть")
                boxes=[el.bounding_box() for el in (menu,left,right)]
                self.assertTrue(all(b is not None for b in boxes))
                for box in boxes[1:]:
                    self.assertAlmostEqual(box["height"],boxes[0]["height"],delta=.1)
                    self.assertAlmostEqual(box["width"],boxes[0]["width"],delta=.1)
                self.assertAlmostEqual(boxes[0]["height"],28.8,delta=.2)
                p.locator("#assistant-form textarea").fill("Черновик")
                left.click()
                expect(helper).not_to_be_visible()
                expect(work).to_be_visible()
                expect(right).to_have_text("Помощник")
                right.click()
                expect(helper).to_be_visible()
                expect(work).to_be_visible()
                expect(right).to_have_text("Свернуть")
                right.click()
                expect(work).not_to_be_visible()
                expect(helper).to_be_visible()
                expect(left).to_have_text("Мастерская")
                left.click()
                expect(helper).to_be_visible()
                expect(work).to_be_visible()
                expect(left).to_have_text("Свернуть")
                expect(p.locator("#assistant-form textarea")).to_have_value("Черновик")
                menu.click()
                expect(nav).not_to_be_visible()
                expect(helper).to_be_visible()
                expect(work).to_be_visible()
                p.locator("#toggle-nav").click()
                expect(nav).to_be_visible()
        p.set_viewport_size({"width":390,"height":844})
        expect(helper).to_be_visible()
        expect(work).not_to_be_visible()
        expect(left).to_have_text("Мастерская")
        left.click()
        expect(work).to_be_visible()
        expect(helper).not_to_be_visible()
        expect(right).to_have_text("Помощник")
        right.click()
        expect(helper).to_be_visible()
        expect(work).not_to_be_visible()
        expect(left).to_have_text("Мастерская")
        self.assertLessEqual(p.evaluate("document.documentElement.scrollWidth * Number(getComputedStyle(document.documentElement).zoom)"),391)
        p.set_viewport_size({"width":1440,"height":1000})
        self.ready()
